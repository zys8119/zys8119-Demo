    type Options = {
        angle: number,
        color: string,
        lineWidth: number
        dash: boolean
        area: boolean | 'left' | 'right'
        animation: boolean
        lineLength: number
    }
    const drawLine = (options: Partial<Options>) => {
        const config = merge<Options, Partial<Options>>({
            angle: 0,
            color: 'red',
            lineWidth: 5,
            dash: true,
            area: false,
            animation: false,
            lineLength: 0.8
        }, options)
        ctx.save()
        ctx.strokeStyle = config.color;
        // 设置虚线样式：[实线长度, 间隔长度]
        if (config.dash) {
            ctx.setLineDash([10, 5]);
        }
        ctx.translate(w / 2, h);
        ctx.rotate(-Math.PI / 180 * (90 + config.angle * (config.animation ? p : 1)));
        ctx.beginPath();
        ctx.moveTo(0, 0);
        ctx.lineTo(h * config.lineLength, 0);
        ctx.stroke();
        if (config.area) {
            ctx.fillStyle = config.color;
            ctx.globalAlpha = 0.1;
            ctx.rect(0, 0, h * config.lineLength, config.area === 'left' ? -h : h);
            ctx.fill();
        }
        ctx.globalAlpha = 1;
        ctx.save()
        ctx.translate(h * config.lineLength, 0);
        ctx.rotate(Math.PI / 180 * (90 + config.angle));
        ctx.fillStyle = config.color;
        ctx.font = '20px Arial';
        ctx.fillText(config.angle.toString() + 'º', -15, -15);
        ctx.restore()
        ctx.restore()
    }
    const lines = [
        { angle: -10, area: 'right', color: 'red' },
        { angle: 10, area: 'left', color: 'red' },
        { angle: 30, dash: false, color: '#004cff', area: false, animation: true }
    ]
    lines.forEach((line: any) => {
        drawLine(line)
    })
    ctx.save()
    ctx.translate(15, 15)
    ctx.font = '15px Arial';
    ctx.fillStyle = 'red'
    ctx.fillRect(0, 0, 10, 10)
    ctx.fillText('安全范围', 15, 10)
    ctx.font = '15px Arial';
    ctx.fillStyle = '#004cff'
    ctx.fillRect(0, 20, 10, 10)
    ctx.fillText('倾斜角度', 15, 30)
    ctx.restore();
}
